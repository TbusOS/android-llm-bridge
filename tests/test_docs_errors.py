"""docs/errors.md lists every error code, and stays that way.

The per-code listing is generated by scripts/gen_errors_doc.py from
alb.infra.errors.ERROR_CODES plus a scan of src/alb for codes that are
returned without being registered. Before it was generated the page had
fallen to 23 of 88 registered codes. This test fails as soon as the catalog
or a returned code changes without the page being regenerated."""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path
from types import ModuleType

import pytest

_SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "gen_errors_doc.py"


def _load() -> ModuleType:
    spec = importlib.util.spec_from_file_location("gen_errors_doc", _SCRIPT)
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    # dataclasses resolve annotations through sys.modules[cls.__module__]
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod


gen = _load()


def test_errors_doc_is_up_to_date():
    problems = gen.check()
    assert problems == [], (
        "docs/errors.md does not match the error catalog; regenerate it with\n"
        "    uv run python scripts/gen_errors_doc.py\n\n" + "\n\n".join(problems)
    )


def test_every_registered_code_is_in_the_doc():
    """Independent of the generator's own comparison: if the block were
    emptied and the check broken with it, this still catches it."""
    from alb.infra.errors import ERROR_CODES

    doc = gen.DOC.read_text(encoding="utf-8")
    missing = sorted(c for c in ERROR_CODES if f"| `{c}` |" not in doc)
    assert missing == [], f"not in docs/errors.md: {missing}"


def _fresh_doc() -> str:
    """The real page with its block regenerated, so the tests below check
    only the change they make, whatever state the page is in."""
    return gen.build(gen.DOC.read_text(encoding="utf-8"))


def test_check_reports_a_stale_suggestion(tmp_path: Path):
    """Guard the guard: a doc whose generated text was edited by hand must
    be reported, with a diff naming the line."""
    from alb.infra.errors import ERROR_CODES

    spec = ERROR_CODES["FLASH_FAILED"]
    doc = _fresh_doc()
    cell = gen._cell(spec.default_suggestion)
    assert cell in doc
    stale = tmp_path / "errors.md"
    stale.write_text(doc.replace(cell, "Just flash it again.", 1), encoding="utf-8")

    problems = gen.check(stale)
    assert len(problems) == 1
    assert "is stale; run: uv run python scripts/gen_errors_doc.py" in problems[0]
    assert (
        "-| `FLASH_FAILED` | fastboot ran but reported a failure | Just flash it again. |"
        in problems[0]
    )


def test_check_reports_a_note_for_an_unknown_code(tmp_path: Path):
    doc = _fresh_doc()
    bad = tmp_path / "errors.md"
    bad.write_text(doc + "\n| `NO_SUCH_CODE_ANYWHERE` | made up |\n", encoding="utf-8")
    problems = gen.check(bad)
    assert len(problems) == 1
    assert "NO_SUCH_CODE_ANYWHERE" in problems[0]


def test_missing_markers_stop_the_generator(tmp_path: Path):
    bad = tmp_path / "errors.md"
    bad.write_text("# no markers here\n", encoding="utf-8")
    with pytest.raises(SystemExit):
        gen.check(bad)


def test_scan_follows_the_ways_a_code_is_chosen(tmp_path: Path):
    """Each construct below is one way src/alb picks a code; each must be
    found, and the two non-returns at the end must not."""
    pkg = tmp_path / "src" / "alb"
    pkg.mkdir(parents=True)
    (pkg / "m.py").write_text(
        """
from dataclasses import dataclass

CODE_CONST = "A_CONST"
_TABLE = {1: "A_TABLE_VALUE", 2: "A_TABLE_OTHER"}

@dataclass
class Res:
    ok: bool
    error_code: str | None = None

def fail(code, message=""):
    return code

def _declined(name, code, why):
    return {"code": code}

def _classify(text):
    if text:
        return "A_CLASSIFIED"
    return "A_FALLBACK"

def _check():
    return {}, "A_TUPLE", "problem"

def run(r, state, text, detail):
    fail("A_POSITIONAL")
    fail(code="A_KEYWORD")
    fail(code=r.error_code or "A_OR_DEFAULT")
    fail(code="A_IF" if r else "A_ELSE")
    fail(CODE_CONST)
    _declined("tool", "A_SECOND_POSITION", "why")
    Res(ok=False, error_code=_classify(text))
    code = _TABLE[state]
    fail(code=code)
    params, code2, problem = _check()
    fail(code=code2)
    out = {"code": detail.get("code", "A_GET_DEFAULT")}
    unused = "NOT_RETURNED_DEAD"
    if r.error_code == "NOT_RETURNED_COMPARED":
        pass
    return out
""",
        encoding="utf-8",
    )
    found = gen.scan_returned_codes(pkg, rel_to=tmp_path)
    assert set(found) == {
        "A_CONST",
        "A_TABLE_VALUE",
        "A_TABLE_OTHER",
        "A_CLASSIFIED",
        "A_FALLBACK",
        "A_TUPLE",
        "A_POSITIONAL",
        "A_KEYWORD",
        "A_OR_DEFAULT",
        "A_IF",
        "A_ELSE",
        "A_SECOND_POSITION",
        "A_GET_DEFAULT",
    }
    assert found["A_KEYWORD"] == {"src/alb/m.py"}


def test_scan_on_the_real_tree_sees_known_returns():
    """Codes returned three common ways: `code=r.error_code or "..."`
    (SHELL_NONZERO_EXIT), a ShellResult field filled by a classifier
    (ADB_COMMAND_FAILED), `fail(code=...)` (PERMISSION_DENIED)."""
    found = gen.scan_returned_codes()
    assert {"ADB_COMMAND_FAILED", "SHELL_NONZERO_EXIT", "PERMISSION_DENIED"} <= set(found)
    assert "src/alb/transport/serial.py" in found["SERIAL_PERMISSION_DENIED"]
    # assigned to a variable that is never used (capabilities/diagnose.py)
    assert "NO_ANR_FOUND" not in found
