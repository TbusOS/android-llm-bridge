#!/usr/bin/env node
/**
 * Copy the v3 stylesheet, fonts and icon set into docs/assets/v3/ so the
 * static design mockups (docs/webui-preview-v3*.html) render with exactly
 * what the React app ships. The React sources are the only place to edit.
 *
 *   node web/scripts/sync_v3_assets.mjs          # write the copies
 *   node web/scripts/sync_v3_assets.mjs --check  # exit 1 if a copy is stale
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "..", "..");
const srcDir = join(repo, "web", "src", "styles", "v3");
const outDir = join(repo, "docs", "assets", "v3");
const check = process.argv.includes("--check");

function cssBundle() {
  const index = readFileSync(join(srcDir, "index.css"), "utf8");
  const parts = [...index.matchAll(/@import\s+"\.\/([^"]+)";/g)].map((m) => m[1]);
  if (parts.length === 0) throw new Error("index.css lists no @import");
  const head = "/* Generated by web/scripts/sync_v3_assets.mjs from web/src/styles/v3/. Do not edit. */\n";
  return head + parts.map((p) => `/* ---- ${p} ---- */\n${readFileSync(join(srcDir, p), "utf8")}`).join("\n");
}

function iconsBundle() {
  const src = readFileSync(join(repo, "web", "src", "components", "v3", "icons.ts"), "utf8");
  const m = src.match(/\/\/ ICONS-JSON-BEGIN\n[^{]*(\{[\s\S]*?\n\});?\n\/\/ ICONS-JSON-END/);
  if (!m) throw new Error("icons.ts: ICONS-JSON markers not found");
  const icons = JSON.parse(m[1]);
  return `/* Generated by web/scripts/sync_v3_assets.mjs from web/src/components/v3/icons.ts. Do not edit. */\nwindow.ALB_ICONS = ${JSON.stringify(icons, null, 1)};\n`;
}

const outputs = new Map([
  [join(outDir, "alb.css"), cssBundle()],
  [join(outDir, "icons.js"), iconsBundle()],
]);
const fontFiles = readdirSync(join(srcDir, "fonts")).filter((f) => /\.(woff2|txt)$/.test(f));

let stale = 0;
for (const [path, text] of outputs) {
  const same = existsSync(path) && readFileSync(path, "utf8") === text;
  if (check) {
    if (!same) { console.error(`stale: ${path}`); stale++; }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
  }
}
for (const f of fontFiles) {
  const from = join(srcDir, "fonts", f);
  const to = join(outDir, "fonts", f);
  const same = existsSync(to) && readFileSync(to).equals(readFileSync(from));
  if (check) {
    if (!same) { console.error(`stale: ${to}`); stale++; }
  } else {
    mkdirSync(dirname(to), { recursive: true });
    copyFileSync(from, to);
  }
}
if (check) {
  if (stale) { console.error(`${stale} file(s) out of date — run node web/scripts/sync_v3_assets.mjs`); process.exit(1); }
  console.log("docs/assets/v3 matches web/src");
} else {
  console.log(`wrote ${outputs.size} files and ${fontFiles.length} font files to docs/assets/v3`);
}
